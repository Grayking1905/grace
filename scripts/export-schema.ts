import { mkdirSync, writeFileSync } from 'node:fs';
import { tables, indexes } from '../server/schema.js';
for (const driver of ['mysql', 'sqlite']) {
  const sql = [
    `-- Grace initial schema, version 1 (${driver}). Generated by npm run db:schema.`,
    ...(driver === 'mysql'
      ? ['-- Use a dedicated database with utf8mb4 encoding.']
      : ['PRAGMA foreign_keys = ON;']),
    '',
    ...Object.entries(tables).map(
      ([name, columns]) =>
        `CREATE TABLE IF NOT EXISTS ${name} (\n  ${columns.replace(/, (?=[a-z`A-Z])/g, ',\n  ')}\n)${driver === 'mysql' ? ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4' : ''};\n`,
    ),
    ...indexes.map(
      ([name, table, columns]) =>
        `CREATE INDEX ${driver === 'sqlite' ? 'IF NOT EXISTS ' : ''}${name} ON ${table} (${columns});`,
    ),
    '',
  ];
  mkdirSync(`database/${driver}`, { recursive: true });
  writeFileSync(`database/${driver}/001_initial.sql`, sql.join('\n'));
  console.log(`Exported database/${driver}/001_initial.sql`);
}
